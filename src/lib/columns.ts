export function pickColumns(available: string[], wanted: string[] | undefined, fallback: string[]): string[] {
  const have = new Set(available)
  const source = wanted && wanted.length ? wanted : fallback
  const picked = source.filter((col) => have.has(col))
  return picked.length ? picked : available.slice(0, Math.min(8, available.length))
}
